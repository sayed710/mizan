import { useEffect } from 'react';
import { addressLines } from '../models/company.js';
import { t } from '../i18n.js';

/** Canonical printable document view for financial reports with company header and footer. */
export function ReportPrintView({ active = true, company, title, subtitle, controls = null, children, onBack, autoPrint = true }) {
  useEffect(() => {
    if (!active || !autoPrint || !company) return;
    window.print();
  }, [active, autoPrint, company]);

  if (active && !company) {
    return (
      <main className="print-page">
        {onBack && (
          <div className="no-print print-toolbar">
            <button type="button" className="btn" onClick={onBack}>{t('Back')}</button>
          </div>
        )}
        <p className="empty" role="alert">{t('Configure the document company before printing.')}</p>
      </main>
    );
  }

  return (
    <main className={active ? 'print-page' : 'action report-page'}>
      {active ? (
        <div className="no-print print-toolbar">
          <button type="button" className="btn primary" onClick={() => window.print()}>{t('Print')}</button>
          <button type="button" className="btn" onClick={onBack ?? (() => history.back())}>{t('Back')}</button>
        </div>
      ) : controls}
      <article className={active ? 'paper' : undefined}>
        {active && (
          <>
            <header className="paper-head">
              <div>
                <b className="paper-company">{company.name}</b>
                {addressLines(company, t('Tax ID')).map((line, i) => <div key={`${i}-${line}`} className="muted">{line}</div>)}
                <div className="muted">{company.currency ?? t('Company currency is not configured')}</div>
              </div>
            </header>
            <h1>{title}</h1>
            {subtitle ? <p className="muted">{subtitle}</p> : null}
          </>
        )}
        {children}
        {active && <footer className="paper-foot muted">{company.name} · {t('Generated by Mizan')}</footer>}
      </article>
    </main>
  );
}
