import { useEffect, useRef } from 'react';
import { addressLines } from '../models/company.js';
import { t } from '../i18n.js';

/** Canonical printable document view for financial reports with company header and footer. */
export function ReportPrintView({
  active = true,
  company,
  companies = null,
  title,
  subtitle,
  controls = null,
  children,
  onBack,
  autoPrint = true,
  documents = null,
}) {
  const printedRef = useRef(false);
  const prevActiveRef = useRef(active);

  const list = Array.isArray(companies) && companies.length > 0 ? companies : (company ? [company] : []);
  const primaryCompany = list[0] ?? company;
  const isMulti = list.length > 1;
  const companyTitle = list.map((c) => c?.name).filter(Boolean).join(', ') || primaryCompany?.name;

  useEffect(() => {
    // Only fire autoPrint on transition from inactive (false) to active (true),
    // representing an explicit user action to print. Never fire on initial mount
    // when active is already true (e.g. reload of a preview tab) and never fire
    // repeatedly on re-render while active remains true.
    if (!prevActiveRef.current && active && autoPrint && primaryCompany && !printedRef.current) {
      printedRef.current = true;
      window.print();
    }
    if (!active) {
      printedRef.current = false;
    }
    prevActiveRef.current = active;
  }, [active, autoPrint, primaryCompany]);

  if (active && !primaryCompany) {
    return (
      <main className="print-page">
        {onBack && (
          <div className="no-print print-toolbar">
            <button type="button" className="btn" onClick={onBack}>{t('Back')}</button>
          </div>
        )}
        <p className="empty" role="alert">{t('Configure the document company before printing.')}</p>
      </main>
    );
  }

  return (
    <main className={active ? 'print-page' : 'action report-page'}>
      {active ? (
        <div className="no-print print-toolbar">
          <button type="button" className="btn primary" onClick={() => window.print()}>{t('Print')}</button>
          <button type="button" className="btn" onClick={onBack ?? (() => history.back())}>{t('Back')}</button>
        </div>
      ) : controls}
      {(active && documents?.length ? documents : [{ key: 'report', content: children }]).map((document, index) => <article key={document.key} className={active ? 'paper' : undefined} style={active && documents?.length && index < documents.length - 1 ? { breakAfter: 'page' } : undefined}>
        {active && (
          <>
            <header className="paper-head">
              <div>
                <b className="paper-company">{companyTitle}</b>
                {!isMulti && primaryCompany && addressLines(primaryCompany, t('Tax ID')).map((line, i) => <div key={`${i}-${line}`} className="muted">{line}</div>)}
                {!isMulti && primaryCompany && <div className="muted">{primaryCompany.currency ?? t('Company currency is not configured')}</div>}
              </div>
            </header>
            <h1>{title}</h1>
            {subtitle ? <p className="muted">{subtitle}</p> : null}
          </>
        )}
        {document.content}
        {active && <footer className="paper-foot muted">{companyTitle} · {t('Generated by Mizan')}</footer>}
      </article>)}
    </main>
  );
}
