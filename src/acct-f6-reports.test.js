// Test 1: XLSX generated bytes are a valid ZIP with OpenXML parts, numeric cells,
// bold header rows, multi-level merged headers, escaped text, and sheet name <= 31 chars.
// ---------------------------------------------------------------------------
test('xlsx: the generated bytes are a valid zip (check local headers, central directory, CRC of each part) and sheet1.xml contains numeric cells for amounts and the escaped labels', async () => {
  const { buildXlsx, parseZip, readXlsx, crc32 } = await import('./xlsx.js');

  const sheetNameVeryLong = 'This Sheet Name Is Exceptionally Long And Must Be Limited';
  const testRows = [
    ['Header <1>', 'Header "2" & 3', 'Amount (USD)', 'Percentage'],
    ['Product & "Service" <A>', 1234.56, '$1,234.56', '15.5%'],
    ['Cost of <Goods> & Materials', -500.0, '-$500.00', '0.00'],
    ['Special "Tax" & Surcharge', 0, '($250.75)', '100%'],
  ];

  const merges = ['A1:B1']; // Multi-level / merged column header
  const xlsxBytes = buildXlsx(testRows, { sheetName: sheetNameVeryLong, merges });

  assert.ok(xlsxBytes instanceof Uint8Array, 'buildXlsx returns a Uint8Array');
  assert.ok(xlsxBytes.length > 500, 'XLSX byte length is realistic');

  // Verify ZIP structure manually (local headers, central directory, CRC of each part)
  const zipInfo = parseZip(xlsxBytes);
  assert.ok(zipInfo.files['[Content_Types].xml'], '[Content_Types].xml exists in zip');
  assert.ok(zipInfo.files['_rels/.rels'], '_rels/.rels exists in zip');
  assert.ok(zipInfo.files['xl/workbook.xml'], 'xl/workbook.xml exists in zip');
  assert.ok(zipInfo.files['xl/_rels/workbook.xml.rels'], 'xl/_rels/workbook.xml.rels exists in zip');
  assert.ok(zipInfo.files['xl/styles.xml'], 'xl/styles.xml exists in zip');
  assert.ok(zipInfo.files['xl/worksheets/sheet1.xml'], 'xl/worksheets/sheet1.xml exists in zip');

  // Check CRC32 of each entry and verify central directory + EOCD
  const fileNames = Object.keys(zipInfo.files);
  for (const [name, file] of Object.entries(zipInfo.files)) {
    const computedCrc = crc32(file.data);
    assert.equal(file.crc, computedCrc, `CRC-32 of ${name} matches stored CRC in header`);
    assert.equal(file.size, file.data.length, `Size of ${name} matches uncompressed data length`);
    assert.equal(file.compression, 0, `${name} is stored without compression`);
  }
  assert.equal(zipInfo.centralDirectory.length, fileNames.length, 'Central directory entry count matches local files');
  for (const cd of zipInfo.centralDirectory) {
    const local = zipInfo.files[cd.filename];
    assert.ok(local, `Central directory entry ${cd.filename} matches a local file`);
    assert.equal(cd.crc, local.crc, `Central directory CRC for ${cd.filename} matches local header`);
    assert.equal(cd.compressedSize, local.compressedSize, `Central directory compressedSize for ${cd.filename} matches`);
    assert.equal(cd.size, local.size, `Central directory size for ${cd.filename} matches`);
    assert.equal(cd.localHeaderOffset, local.offset, `Central directory offset for ${cd.filename} matches local header`);
  }
  assert.ok(zipInfo.eocd, 'End of central directory record exists');
  assert.equal(zipInfo.eocd.entriesOnDisk, fileNames.length, 'EOCD entriesOnDisk matches file count');
  assert.equal(zipInfo.eocd.totalEntries, fileNames.length, 'EOCD totalEntries matches file count');
  assert.equal(zipInfo.eocd.centralOffset, zipInfo.eocd.actualCentralOffset, 'EOCD centralOffset matches actual offset');

  // Check workbook.xml for sheet name limited to 31 characters
  const workbookXml = new TextDecoder().decode(zipInfo.files['xl/workbook.xml'].data);
  const sheetMatch = workbookXml.match(/<sheet[^>]*name="([^"]+)"/);
  assert.ok(sheetMatch, 'sheet tag found in workbook.xml');
  assert.ok(sheetMatch[1].length <= 31, `Sheet name is limited to 31 chars (got ${sheetMatch[1].length})`);

  // Check styles.xml for bold font and custom number format
  const stylesXml = new TextDecoder().decode(zipInfo.files['xl/styles.xml'].data);
  assert.ok(stylesXml.includes('<b/>'), 'styles.xml includes bold font for headers');
  assert.ok(stylesXml.includes('numFmtId="164"'), 'styles.xml includes number format');

  // Check sheet1.xml contains numeric cells (<v>...) and escaped labels
  const sheet1Xml = new TextDecoder().decode(zipInfo.files['xl/worksheets/sheet1.xml'].data);
  assert.ok(sheet1Xml.includes('&lt;Goods&gt; &amp; Materials') || sheet1Xml.includes('Cost of &lt;Goods&gt; &amp; Materials'), 'sheet1.xml XML-escapes <, >, &');
  assert.ok(sheet1Xml.includes('&quot;Service&quot;') || sheet1Xml.includes('&quot;'), 'sheet1.xml XML-escapes quotes');
  assert.ok(sheet1Xml.includes('<mergeCell ref="A1:B1"'), 'sheet1.xml contains mergeCell for multi-level column header');
  assert.ok(sheet1Xml.includes('<c r="A1" s="1"'), 'sheet1.xml marks header cells bold (s="1")');
  assert.ok(sheet1Xml.includes('<c r="B2" s="2"><v>1234.56</v></c>'), 'sheet1.xml writes numeric cell with number format style (s="2")');
  // Numeric cells have number format and <v>
  assert.ok(sheet1Xml.includes('<v>1234.56</v>') || sheet1Xml.includes('<v>1234.560'), 'sheet1.xml contains numeric cell for 1234.56');
  assert.ok(sheet1Xml.includes('<v>-500</v>') || sheet1Xml.includes('<v>-500.00</v>'), 'sheet1.xml contains numeric cell for negative amount');
  assert.ok(sheet1Xml.includes('<v>-250.75</v>'), 'sheet1.xml parses parenthesized negative currency amount to -250.75');

  // Parse rows back and check
  const parsed = readXlsx(xlsxBytes);
  assert.equal(parsed.sheetName.length <= 31, true);
  assert.equal(parsed.rows.length, 4);
});

