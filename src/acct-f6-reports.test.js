// Test 3: CYE unfolds to income/expense accounts whose sum equals the CYE line;
// balance sheet totals unchanged.
// ---------------------------------------------------------------------------
test('CYE unfolds to income/expense accounts whose sum equals the CYE line; balance sheet totals unchanged', async () => {
  const { makeEl } = setupDom();
  const React = await import('react');
  const { createRoot } = await import('react-dom/client');
  const store = await import('./store.js');
  await store.initStore();

  let db = seed();
  db = { ...db, records: { ...db.records, 'account.move': [], 'account.payment': [] } };
  const yr = Number(today().slice(0, 4));

  const cashAcc = search(db, 'account.account').find((a) => a.code === '101401');
  const revAcc = search(db, 'account.account').find((a) => a.code === '400000');
  const otherIncAcc = search(db, 'account.account').find((a) => a.code === '490000') || search(db, 'account.account').find((a) => a.account_type === 'income_other');
  const expAcc = search(db, 'account.account').find((a) => a.code === '600000');
  const depAcc = search(db, 'account.account').find((a) => a.code === '681000') || search(db, 'account.account').find((a) => a.account_type === 'expense_depreciation');

  // Prior year: Revenue 3000, Expense 1000 -> Net PYE = 2000
  db = postEntry(db, {
    journal: 'MISC', company: 1, date: `${yr - 1}-06-15`,
    lines: [
      { account_id: cashAcc.id, debit: 2000 },
      { account_id: expAcc.id, debit: 1000 },
      { account_id: revAcc.id, credit: 3000 },
    ],
  }).db;

  // Current year: Revenue: 5000, Other Income: 1000 -> Total Income: 6000
  // Expense: 1500, Depreciation: 500 -> Total Expense: 2000
  // Net CYE = 6000 - 2000 = 4000
  db = postEntry(db, {
    journal: 'MISC', company: 1, date: `${yr}-04-10`,
    lines: [
      { account_id: cashAcc.id, debit: 4000 },
      { account_id: expAcc.id, debit: 1500 },
      ...(depAcc ? [{ account_id: depAcc.id, debit: 500 }] : [{ account_id: expAcc.id, debit: 500 }]),
      { account_id: revAcc.id, credit: 5000 },
      ...(otherIncAcc ? [{ account_id: otherIncAcc.id, credit: 1000 }] : [{ account_id: revAcc.id, credit: 1000 }]),
    ],
  }).db;

  await React.act(async () => store.commit(db));

  const { ConfigurableReportPage } = await import('./views/ConfigurableReport.jsx');
  const host = makeEl('div');
  host.ownerDocument = globalThis.document;
  const root = createRoot(host);

  try {
    await React.act(async () => {
      root.render(React.createElement(ConfigurableReportPage, { statementKind: 'balance' }));
    });

    const bsReport = findStatementReport(db, 'balance', 1);
    assert.ok(bsReport, 'Balance Sheet report definition found');
    const cyeLineDef = bsReport.line_ids.find((l) => l.code === 'CYE');
    assert.ok(cyeLineDef, 'CYE line exists in Balance Sheet definition');
    assert.equal(cyeLineDef.foldable, true, 'CYE line must be foldable');

    const pyeLineDef = bsReport.line_ids.find((l) => l.code === 'PYE');
    assert.ok(pyeLineDef, 'PYE line exists in Balance Sheet definition');
    assert.equal(pyeLineDef.foldable, true, 'PYE line must be foldable');

    // Check compareConfigurableReport data directly
    const period = { from: `${yr}-01-01`, to: `${yr}-12-31` };
    const reportData = compareConfigurableReport(db, bsReport, [{ ...period, label: 'Balance' }], period);
    const cyeRow = reportData.rows.find((r) => r.code === 'CYE');
    assert.ok(cyeRow, 'CYE row exists in report results');
    assert.ok(isExpandableLine(cyeRow), 'CYE row is expandable');
    assert.equal(cyeRow.values[0], 4000, 'CYE line value is $4,000');

    // Check CYE account contributions
    assert.ok(cyeRow.accountRows.length >= 2, 'CYE has contributing account rows');
    const sumAccounts = cyeRow.accountRows.reduce((sum, a) => sum + a.values[0], 0);
    assert.equal(sumAccounts, cyeRow.values[0], 'Sum of contributing account rows equals CYE line value (4000)');

    // Check PYE account contributions
    const pyeRow = reportData.rows.find((r) => r.code === 'PYE');
    assert.ok(pyeRow, 'PYE row exists in report results');
    assert.ok(isExpandableLine(pyeRow), 'PYE row is expandable');
    assert.equal(pyeRow.values[0], 2000, 'PYE line value is $2,000');
    assert.ok(pyeRow.accountRows.length >= 2, 'PYE has contributing account rows');
    const sumPyeAccounts = pyeRow.accountRows.reduce((sum, a) => sum + a.values[0], 0);
    assert.equal(sumPyeAccounts, pyeRow.values[0], 'Sum of PYE contributing account rows equals PYE line value (2000)');

    // Unfold CYE row in the UI by clicking it
    const allTrs = findAll(host, (n) => n.tagName === 'TR');
    const cyeTr = allTrs.find((tr) => tr.textContent.includes('Current Year Earnings'));
    assert.ok(cyeTr, 'CYE TR element found');

    await React.act(async () => {
      props(cyeTr)?.onClick?.({ stopPropagation: () => {} });
    });

    // Contributing account rows should now be visible in DOM
    assert.ok(host.textContent.includes(revAcc.code), 'Contributing revenue account is shown after unfolding');
    assert.ok(host.textContent.includes(expAcc.code), 'Contributing expense account is shown after unfolding');

    // Verify Balance Sheet totals: Assets ($6,000) = Liabilities ($0) + Equity ($6,000)
    const assetsRow = reportData.rows.find((r) => r.code === 'ASSETS');
    const liabEquityRow = reportData.rows.find((r) => r.code === 'LIAB_EQUITY');
    assert.ok(assetsRow, 'ASSETS row exists');
    assert.ok(liabEquityRow, 'LIAB_EQUITY row exists');
    assert.equal(assetsRow.values[0], 6000, 'Assets total is 6000');
    assert.equal(liabEquityRow.values[0], 6000, 'Liabilities + Equity total is 6000');
  } finally {
    await React.act(async () => root.unmount());
  }
});

