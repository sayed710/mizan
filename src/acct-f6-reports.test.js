// Test 2: The XLSX rows equal the CSV rows for the balance sheet.
// ---------------------------------------------------------------------------
test('the XLSX rows equal the CSV rows for the balance sheet', async () => {
  const { makeEl } = setupDom();
  const React = await import('react');
  const { createRoot } = await import('react-dom/client');
  const store = await import('./store.js');
  await store.initStore();

  let db = seed();
  db = { ...db, records: { ...db.records, 'account.move': [], 'account.payment': [] } };
  const yr = Number(today().slice(0, 4));

  const cashAcc = search(db, 'account.account').find((a) => a.code === '101401');
  const revAcc = search(db, 'account.account').find((a) => a.code === '400000');
  const expAcc = search(db, 'account.account').find((a) => a.code === '600000');

  db = postEntry(db, {
    journal: 'MISC', company: 1, date: `${yr}-03-15`,
    lines: [
      { account_id: cashAcc.id, debit: 1500 },
      { account_id: expAcc.id, debit: 500 },
      { account_id: revAcc.id, credit: 2000 },
    ],
  }).db;

  await React.act(async () => store.commit(db));

  const { ConfigurableReportPage } = await import('./views/ConfigurableReport.jsx');
  const { buildXlsx, readXlsx } = await import('./xlsx.js');

  const host = makeEl('div');
  host.ownerDocument = globalThis.document;
  const root = createRoot(host);

  try {
    await React.act(async () => {
      root.render(React.createElement(ConfigurableReportPage, { statementKind: 'balance' }));
    });

    const table = find(host, (n) => n.tagName === 'TABLE');
    assert.ok(table, 'Balance Sheet table is rendered');

    // Both exports build their rows from tableToRows(tableRef.current)
    const csvRows = tableToRows(table);
    assert.ok(csvRows.length > 0, 'CSV rows extracted');

    const xlsxBytes = buildXlsx(table);
    const parsedXlsx = readXlsx(xlsxBytes);

    // Verify row count matches
    assert.equal(parsedXlsx.rows.length, csvRows.length, 'XLSX rows count equals CSV rows count');

    // Helper to clean/normalize amounts and whitespace
    const norm = (v) => {
      if (v == null) return '';
      if (typeof v === 'number') return v;
      const s = String(v).replace(/[\u200E\u200F\u061C\u202A-\u202E\u2066-\u2069]/g, '').trim();
      const numMatch = s.replace(/[$€£¥\s]/g, '').replace(/,/g, '');
      const paren = numMatch.match(/^\((.*)\)$/);
      if (paren) {
        const val = Number(paren[1]);
        if (Number.isFinite(val)) return -val;
      }
      const parsedNum = Number(numMatch);
      if (!Number.isNaN(parsedNum) && /^[-+]?\d+(?:\.\d+)?$/.test(numMatch)) return parsedNum;
      return s;
    };

    for (let r = 0; r < csvRows.length; r++) {
      const csvRow = csvRows[r].map(norm);
      const xlsxRow = parsedXlsx.rows[r].map(norm);
      assert.deepEqual(xlsxRow, csvRow, `Row ${r} matches between XLSX and CSV`);
    }

    // Verify "Export XLSX" button exists next to CSV / Print buttons
    const exportXlsxBtn = find(host, (n) => n.tagName === 'BUTTON' && n.textContent.includes('Export XLSX'));
    assert.ok(exportXlsxBtn, 'Export XLSX button exists on ConfigurableReportPage');
  } finally {
    await React.act(async () => root.unmount());
  }
});

