// Test 4: Custom account.report respects the analytic filter.
// ---------------------------------------------------------------------------
test('a custom account.report respects the analytic filter', async () => {
  const { makeEl } = setupDom();
  const React = await import('react');
  const { createRoot } = await import('react-dom/client');
  const store = await import('./store.js');
  await store.initStore();

  let db = seed();
  db = { ...db, records: { ...db.records, 'account.move': [], 'account.payment': [] } };
  const yr = Number(today().slice(0, 4));

  const planId = db.records['account.analytic.plan'][0].id;
  const aAlpha = create(db, 'account.analytic.account', { name: 'Alpha Project', company_id: 1, plan_id: planId }); db = aAlpha.db;
  const aBeta = create(db, 'account.analytic.account', { name: 'Beta Project', company_id: 1, plan_id: planId }); db = aBeta.db;

  const cashAcc = search(db, 'account.account').find((a) => a.code === '101401');
  const revAcc = search(db, 'account.account').find((a) => a.code === '400000');

  // Entry with analytic distribution: 70% Alpha ($700) and 30% Beta ($300)
  db = postEntry(db, {
    journal: 'MISC', company: 1, date: `${yr}-05-20`,
    lines: [
      { account_id: cashAcc.id, debit: 1000 },
      {
        account_id: revAcc.id, credit: 1000,
        analytic_distribution: { [aAlpha.id]: 70, [aBeta.id]: 30 },
      },
    ],
  }).db;

  // Custom report with revenue line
  const customReport = create(db, 'account.report', {
    name: 'Custom Revenue Statement',
    company_id: 1,
    date_scope: 'range',
    line_ids: [
      { name: 'Total Revenue', code: 'TREV', sequence: 10, parent_code: '', formula: '400000', sign: -1, foldable: false, strong: true },
    ],
  });
  db = customReport.db;

  await React.act(async () => store.commit(db));

  const { ConfigurableReportPage } = await import('./views/ConfigurableReport.jsx');
  const host = makeEl('div');
  host.ownerDocument = globalThis.document;
  const root = createRoot(host);

  try {
    await React.act(async () => {
      root.render(React.createElement(ConfigurableReportPage, { id: customReport.id }));
    });

    // Unfiltered total: $1,000.00
    assert.ok(host.textContent.includes('$1,000.00'), 'Initial unfiltered custom report total is $1,000.00');

    // Filter by Alpha (70% -> $700.00)
    const analyticSelect = find(host, (n) => n.tagName === 'SELECT' && props(n)?.['aria-label'] === 'Analytic Accounts');
    assert.ok(analyticSelect, 'Analytic Accounts multi-select rendered on custom report');

    await React.act(async () => {
      props(analyticSelect).onChange({ target: { selectedOptions: [{ value: String(aAlpha.id) }] } });
    });

    assert.ok(host.textContent.includes('$700.00'), 'Custom report total is filtered to $700.00 for Alpha');
    assert.ok(!host.textContent.includes('$1,000.00'), 'Unfiltered $1,000.00 does not appear when filtered');

    // Filter by Beta (30% -> $300.00)
    await React.act(async () => {
      props(analyticSelect).onChange({ target: { selectedOptions: [{ value: String(aBeta.id) }] } });
    });

    assert.ok(host.textContent.includes('$300.00'), 'Custom report total is filtered to $300.00 for Beta');
    assert.ok(!host.textContent.includes('$700.00'), 'Alpha amount does not appear when filtered to Beta');
  } finally {
    await React.act(async () => root.unmount());
  }
});

