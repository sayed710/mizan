import { seed } from '../src/seed.js';
import { create, read, search, write } from '../src/orm.js';
import { createCompany, ensureMainCompany } from '../src/models/company.js';
import { postMove } from '../src/models/accounting.js';
import { consolidate } from '../src/models/consolidation.js';
let db = ensureMainCompany(seed());
const eur = search(db, 'res.currency').find((c) => c.name === 'EUR');
const usd = search(db, 'res.currency').find((c) => c.name === 'USD') ?? create(db, 'res.currency', { name: 'USD', rate_ids: [] });
if (!search(db, 'res.currency').find((c) => c.name === 'USD')) db = usd.db;
const usdId = search(db, 'res.currency').find((c) => c.name === 'USD').id;
const sub = createCompany(db, { name: 'EU Sub', currency_id: eur.id });
db = sub.db;
console.log('settings.currency', db.settings.currency, '| EU Sub currency', read(db, 'res.company', sub.id).currency_id === eur.id ? 'EUR' : '?');
const c = create(db, 'account.move', { move_type: 'out_invoice', company_id: sub.id, partner_id: 3, currency_id: eur.id, invoice_date: '2026-10-01', invoice_line_ids: [{ name: 'x', qty: 1, price_unit: 100, tax: 0 }] });
db = postMove(c.db, c.id);
const m = read(db, 'account.move', c.id);
console.log('EUR 100 invoice in EUR-functional company booked as', JSON.stringify(m.line_ids.map((l) => [l.name, l.debit, l.credit])));
const chart = create(db, 'consolidation.chart', { name: 'G', currency_id: usdId, company_ids: [{ company_id: sub.id, ownership: 100, method: 'full' }], account_ids: [{ code: 'AR', name: 'AR', account_type: 'asset_receivable', source_codes: '121000' }] });
const period = create(chart.db, 'consolidation.period', { name: 'Oct', chart_id: chart.id, date_from: '2026-10-01', date_to: '2026-10-31' });
const res = consolidate(period.db, period.id);
console.log('consolidated AR in USD (expected 100/0.92 = 108.70):', res.lines[0].total);
