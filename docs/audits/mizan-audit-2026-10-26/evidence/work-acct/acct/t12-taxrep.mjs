import { seed } from '../src/seed.js';
import { create, search } from '../src/orm.js';
import { postMove } from '../src/models/accounting.js';
import { taxReport, taxesByTax } from '../src/models/finance.js';
import { startSession, payOrder, priceLines } from '../src/models/pos.js';
const P = { from: '2026-10-01', to: '2026-10-31' };
const base = seed();
const show = (label, db) => { const t = taxReport(db, P); const s = taxesByTax(db, P).filter((x) => x.side === 'sale'); console.log(label, '| journal output VAT', t.output, '| per-tax table sale tax sum', Math.round(s.reduce((a, x) => a + x.tax, 0) * 100) / 100); };
show('seed', base);
const eur = search(base, 'res.currency').find((c) => c.name === 'EUR');
let c = create(base, 'account.move', { move_type: 'out_invoice', partner_id: 3, currency_id: eur.id, invoice_date: '2026-10-02', invoice_line_ids: [{ name: 'x', qty: 1, price_unit: 1000, tax: 14 }] });
let db = postMove(c.db, c.id);
show('+ EUR 1000 invoice @0.92', db);
const cb = search(base, 'account.tax').find((t) => t.tax_exigibility === 'on_payment');
c = create(db, 'account.move', { move_type: 'out_invoice', partner_id: 3, invoice_date: '2026-10-02', invoice_line_ids: [{ name: 'cb', qty: 1, price_unit: 1000, tax: 14, tax_cash_basis: true, tax_account_id: cb.account_id }] });
db = postMove(c.db, c.id);
show('+ unpaid cash-basis 1000 invoice', db);
db = startSession(db, 0).db;
const prod = search(db, 'product').find((p) => p.sale_ok !== false && p.type === 'service') ?? search(db, 'product')[0];
db = payOrder(db, { lines: priceLines(db, [{ product_id: prod.id, qty: 1 }]), method: 'card' }).db;
show('+ POS sale (dated today)', db);
